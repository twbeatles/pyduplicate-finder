def missing_widgets(window: Any, page: str) -> list[str]:
    """``page`` 빌더가 할당해야 할 속성 중 window에 없는 이름 목록."""
    required = REQUIRED_WIDGETS.get(page, frozenset())
    return sorted(name for name in required if not hasattr(window, name))


